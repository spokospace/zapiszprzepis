import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { glob, type Loader, type LoaderContext } from 'astro/loaders';
import { frontmatterEnd, nonEmpty, stripFrontmatter, stripInlineMarkdown } from './markdown-text';
import { ALL_SOURCES, entryId, githubUrlForFile, sourceOf, virtualFilePath, type DocSource } from './sources';

/**
 * Starlight's `docs` collection, fed by one Astro `glob()` per repository
 * folder in `ALL_SOURCES`. Entry ids carry the folder's prefix, which is what
 * the sidebar groups by.
 */
export function repoDocsLoader(): Loader {
  return {
    name: 'repo-docs-loader',
    async load(context) {
      for (const source of ALL_SOURCES) {
        await loadSource(source, context as ContextWithEntryTypes);
      }
    },
  };
}

async function loadSource(source: DocSource, context: ContextWithEntryTypes): Promise<void> {
  const external = source.prefix !== '';
  const loader = glob({
    base: source.base,
    // `_`-prefixed files are drafts/partials, as in Starlight's own loader.
    pattern: '**/[^_]*.md',
    generateId: ({ entry }) => entryId(source, entry),
  });

  const scoped: ContextWithEntryTypes = {
    ...context,
    store: scopedStore(context.store, source, external),
    entryTypes: new Map(context.entryTypes).set(
      '.md',
      tolerantFrontmatter(context.entryTypes.get('.md')!, context.logger),
    ),
    async parseData({ id, data, filePath }) {
      // glob() always passes the file it read.
      const absolute = path.resolve(filePath!);
      // Starlight requires `title`; most of these files have none, so it comes
      // from the first `# ` heading, else the file name. No file is edited.
      const title = nonEmpty(data.title) ?? (await deriveTitle(absolute));
      // The stored filePath is virtual (see scopedStore), so "Edit page" is
      // pointed at the real file explicitly.
      const editUrl = external && data.editUrl === undefined ? githubUrlForFile(absolute, 'edit') : data.editUrl;
      return context.parseData({ id, filePath, data: { ...data, title, editUrl } });
    },
  };
  await loader.load(scoped);
}

type Store = LoaderContext['store'];

/**
 * The shared store as one source should see it.
 *
 * - `keys()` lists only this source's ids: `glob()` deletes every key it did
 *   not touch at the end of its load, so unscoped, each glob would wipe the
 *   others' entries.
 * - For a folder outside `src/content/docs/`, `set()` stores the entry under
 *   its {@link virtualFilePath}, because Starlight builds autogenerated sidebar
 *   groups from `filePath` under that folder. The entry has already been
 *   rendered from the real file by then.
 */
function scopedStore(store: Store, source: DocSource, virtualPaths: boolean): Store {
  return new Proxy(store, {
    get(target, prop, receiver) {
      if (prop === 'keys') return () => [...target.keys()].filter((id) => sourceOf(id) === source);
      if (prop === 'set' && virtualPaths) {
        return (entry: Parameters<Store['set']>[0]) =>
          target.set(entry.filePath ? { ...entry, filePath: virtualFilePath(entry.id, entry.filePath) } : entry);
      }
      const value = Reflect.get(target, prop, receiver);
      // Store methods rely on `this`.
      return typeof value === 'function' ? value.bind(target) : value;
    },
  });
}

/**
 * Astro hands every loader its content entry types (`.md` -> frontmatter
 * parser and renderer) and `glob()` reads them, but the public `LoaderContext`
 * type leaves the field out. This is the part of it used here.
 */
interface EntryType {
  getEntryInfo(params: { contents: string; fileUrl: URL }): Promise<{ data: Record<string, unknown>; body: string }>;
}
type ContextWithEntryTypes = LoaderContext & { entryTypes: Map<string, EntryType> };

/**
 * The `.md` parser, except that frontmatter which is not valid YAML (an
 * unquoted `title: A: B`) is read line by line with a warning instead of
 * aborting the whole content sync. The file itself is left as it is.
 */
function tolerantFrontmatter(type: EntryType, logger: LoaderContext['logger']): EntryType {
  return {
    ...type,
    async getEntryInfo(params) {
      try {
        return await type.getEntryInfo(params);
      } catch (error) {
        const { contents, fileUrl } = params;
        const end = frontmatterEnd(contents);
        if (end === -1) throw error;
        logger.warn(
          `Invalid YAML frontmatter in ${fileUrl.pathname}, read line by line instead: ${
            (error as Error).message.split('\n')[0]
          }`,
        );
        return { data: looseFrontmatter(contents.slice(3, end)), body: stripFrontmatter(contents).trim() };
      }
    },
  };
}

/** Top-level `key: value` pairs only; nested blocks and lists are skipped. */
function looseFrontmatter(raw: string): Record<string, string> {
  const data: Record<string, string> = {};
  for (const line of raw.split(/\r?\n/)) {
    const match = /^([A-Za-z_][\w-]*):\s+(.+)$/.exec(line);
    if (match) data[match[1]] = match[2].trim().replace(/^(['"])(.*)\1$/, '$2');
  }
  return data;
}

const HEADING = /^#\s+(.+?)\s*#*\s*$/m;

async function deriveTitle(absolutePath: string): Promise<string> {
  const heading = HEADING.exec(stripFrontmatter(await readFile(absolutePath, 'utf8')))?.[1];
  return heading ? stripInlineMarkdown(heading) : humanizeFileName(absolutePath);
}

const GENERIC_NAMES = new Set(['change', 'plan', 'research', 'verification', 'readme', 'index', 'notes']);

/**
 * `health-check.md` -> `Health check`; `change.md` in `voice-search/` ->
 * `Voice search: change`, since dozens of change folders share that file name.
 */
function humanizeFileName(absolutePath: string): string {
  const words = (name: string) => name.replace(/\.mdx?$/i, '').replace(/[-_]+/g, ' ').trim();
  const capitalize = (text: string) => text.charAt(0).toUpperCase() + text.slice(1);
  const name = words(path.basename(absolutePath));
  if (!GENERIC_NAMES.has(name.toLowerCase())) return capitalize(name);
  return `${capitalize(words(path.basename(path.dirname(absolutePath))))}: ${name.toLowerCase()}`;
}
