import { fileURLToPath } from 'node:url';
import path from 'node:path';

/**
 * The folders of the repository that the docs site renders, and the sidebar
 * group each one becomes. Paths are relative to this Astro project (`docs/`),
 * so `..` is the repository root. Nothing is copied: the content collection
 * reads these folders in place, and a new file in any of them shows up in the
 * sidebar on the next build.
 */
export interface DocSource {
  /** Route and sidebar prefix, e.g. `foundation` -> `/foundation/<slug>/`. */
  prefix: string;
  /** Sidebar group label. */
  label: string;
  /** Folder, relative to the Astro project root. */
  base: string;
}

export const DOC_SOURCES: DocSource[] = [
  { prefix: 'foundation', label: 'Foundation', base: '../context/foundation' },
  { prefix: 'specs', label: 'Specs', base: '../.ai/specs' },
  { prefix: 'changes', label: 'Changes', base: '../context/changes' },
];

/** Starlight's own content folder, relative to the Astro project root. */
const STARLIGHT_DOCS_DIR = 'src/content/docs';

/** The site's own pages (the landing page), kept in Starlight's folder. */
export const SITE_SOURCE: DocSource = { prefix: '', label: 'Site', base: STARLIGHT_DOCS_DIR };

export const ALL_SOURCES = [SITE_SOURCE, ...DOC_SOURCES];

/** The GitHub tree that "Edit page" links and unresolved file links point at. */
export const REPO_URL = 'https://github.com/spokospace/zapiszprzepis';
export const REPO_BRANCH = 'master';

const PROJECT_ROOT = fileURLToPath(new URL('../../', import.meta.url));
const REPO_ROOT = path.resolve(PROJECT_ROOT, '..');

/** The source an entry id belongs to, by its first path segment. */
export function sourceOf(id: string): DocSource {
  const first = id.split('/')[0];
  return DOC_SOURCES.find((s) => s.prefix === first) ?? SITE_SOURCE;
}

/** Lower-case, ASCII-only slug of one path segment (`2026-10-16 Favorites` -> `2026-10-16-favorites`). */
function slugSegment(segment: string): string {
  return segment
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

/**
 * Collection entry id (and therefore route) for a file inside a source.
 * `entry` is the path relative to the source base, forward slashes.
 * `README.md` and `index.md` stand for their folder.
 */
export function entryId(source: DocSource, entry: string): string {
  const segments = entry.replace(/\.mdx?$/i, '').split('/').map(slugSegment).filter(Boolean);
  const last = segments[segments.length - 1];
  if (last === 'index' || last === 'readme') segments.pop();
  if (source.prefix) segments.unshift(source.prefix);
  return segments.join('/') || 'index';
}

/** `absolutePath` relative to `base` with forward slashes, or `undefined` when it lies outside. */
function relativeInside(base: string, absolutePath: string): string | undefined {
  const rel = path.relative(base, absolutePath);
  if (rel.startsWith('..') || path.isAbsolute(rel)) return undefined;
  return rel.split(path.sep).join('/');
}

/** The rendered source an absolute Markdown path belongs to, with its entry id. */
function locate(absolutePath: string): { source: DocSource; id: string } | undefined {
  for (const source of ALL_SOURCES) {
    const rel = relativeInside(path.resolve(PROJECT_ROOT, source.base), absolutePath);
    if (rel === undefined) continue;
    return /\.mdx?$/i.test(rel) ? { source, id: entryId(source, rel) } : undefined;
  }
  return undefined;
}

/**
 * Route for an absolute Markdown file path, or `undefined` when the file is not
 * part of any rendered source. Used to rewrite relative links between docs.
 */
export function routeForFile(absolutePath: string): string | undefined {
  const found = locate(absolutePath);
  if (!found) return undefined;
  return found.id === 'index' ? '/' : `/${found.id}/`;
}

/**
 * Absolute {@link virtualFilePath} of a repository doc, or `undefined` for the
 * site's own pages, which are stored where they are.
 */
export function virtualPathForFile(absolutePath: string): string | undefined {
  const found = locate(absolutePath);
  if (!found || found.source === SITE_SOURCE) return undefined;
  return path.resolve(PROJECT_ROOT, virtualFilePath(found.id, absolutePath.split(path.sep).join('/')));
}

/** GitHub URL of a repository file: its page (`blob`) or its editor (`edit`). */
export function githubUrlForFile(absolutePath: string, mode: 'blob' | 'edit' = 'blob'): string | undefined {
  const rel = relativeInside(REPO_ROOT, absolutePath);
  return rel === undefined ? undefined : `${REPO_URL}/${mode}/${REPO_BRANCH}/${rel}`;
}

/**
 * Where the entry would live if it sat in Starlight's own content folder.
 * Starlight builds autogenerated sidebar groups from `entry.filePath` under
 * `src/content/docs/`, not from the id, so entries read from elsewhere are
 * stored with this path. A folder's `README.md` becomes its `index.md`.
 */
export function virtualFilePath(id: string, originalFilePath: string): string {
  const isFolderIndex = /(^|\/)(readme|index)\.mdx?$/i.test(originalFilePath);
  // The root id is already `index`; `index/index` would be a folder of its own.
  const name = isFolderIndex && id !== 'index' ? `${id}/index` : id;
  return `${STARLIGHT_DOCS_DIR}/${name}.md`;
}
